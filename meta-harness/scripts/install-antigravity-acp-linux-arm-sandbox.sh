#!/usr/bin/env bash
# Sandbox only: installs the Antigravity ACP server on a Linux ARM64 sandbox whose
# kernel uses 16 KiB pages (e.g. VMs on Apple Silicon). Not for macOS or regular hosts;
# use install-antigravity-acp.sh there.
#
# Google's linux-arm64 agy_acp_server.par aborts on 16 KiB pages (it hardcodes 4 KiB),
# so this runs the x86_64 server under QEMU user-mode (>= 8.1, whose x86 guest has
# 4 KiB pages). localharness_external is a static Go binary without that limit and
# must stay native arm64: emulating it corrupts its runtime.
#
# Result: TARGET_DIR/agy_acp_server.par is a wrapper the meta-harness server finds via
# $HOME/.local/share/antigravity-acp (or AGY_EXECUTABLE). Safe to re-run.
set -euo pipefail

ACP_VERSION="${ACP_VERSION:-1.1.1}"
TARGET_DIR="${1:-${HOME}/.local/share/antigravity-acp}"
QEMU_DIR="${QEMU_DIR:-/opt/qemu-user}"
SYSROOT="${SYSROOT:-/opt/x86_64-sysroot}"

ACP_BASE="https://dl.google.com/agy-extensions/releases/linux/agy-acp-server-agy_acp_server_${ACP_VERSION}-linux"
QEMU_POOL="http://deb.debian.org/debian/pool/main/q/qemu/"
GLIBC_POOL="http://archive.ubuntu.com/ubuntu/pool/main/g/glibc/"

SUDO=""
[[ "$(id -u)" -eq 0 ]] || SUDO="sudo"

say() { echo "==> $*"; }
# ELF e_machine: 62 = x86_64, 183 = aarch64
elf_machine() { od -An -j18 -N1 -tu1 "$1" 2>/dev/null | tr -d '[:space:]'; }

if [[ "$(uname -s)" != "Linux" || "$(uname -m)" != "aarch64" ]]; then
  echo "This installer is for Linux ARM64 sandboxes only; use install-antigravity-acp.sh." >&2
  exit 1
fi
if [[ "$(getconf PAGE_SIZE)" == "4096" ]]; then
  echo "Kernel uses 4 KiB pages; the native build works here. Use install-antigravity-acp.sh." >&2
  exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

# 1. The ACP harness drops privileges to group `nobody` and aborts if it is missing.
if ! getent group nobody >/dev/null; then
  say "Creating group nobody"
  ${SUDO} groupadd -r nobody
fi

# 2. Static qemu-x86_64 >= 8.1 (older QEMU reports the host's 16 KiB page size to the guest).
if [[ ! -x "${QEMU_DIR}/bin/qemu-x86_64" ]]; then
  deb="$(curl -fsSL "${QEMU_POOL}" | grep -oE 'qemu-user_10\.[0-9.]+\+ds-0\+deb13u[0-9]+_arm64\.deb' | sort -uV | tail -1)"
  [[ -n "${deb}" ]] || { echo "Could not find a Debian qemu-user 10.x arm64 package" >&2; exit 1; }
  say "Installing ${deb} -> ${QEMU_DIR}"
  curl -fsSL "${QEMU_POOL}${deb}" -o "${TMP}/qemu.deb"
  dpkg-deb -x "${TMP}/qemu.deb" "${TMP}/qemu"
  ${SUDO} install -D -m 0755 "${TMP}/qemu/usr/bin/qemu-x86_64" "${QEMU_DIR}/bin/qemu-x86_64"
fi
"${QEMU_DIR}/bin/qemu-x86_64" --version | head -1

# 3. x86_64 glibc for the emulated server (it only links glibc).
if [[ ! -e "${SYSROOT}/lib/x86_64-linux-gnu/libc.so.6" ]]; then
  deb="$(curl -fsSL "${GLIBC_POOL}" | grep -oE 'libc6_2\.35-0ubuntu3\.[0-9]+_amd64\.deb' | sort -uV | tail -1)"
  [[ -n "${deb}" ]] || { echo "Could not find an Ubuntu libc6 amd64 package" >&2; exit 1; }
  say "Installing ${deb} -> ${SYSROOT}"
  curl -fsSL "${GLIBC_POOL}${deb}" -o "${TMP}/libc6.deb"
  ${SUDO} mkdir -p "${SYSROOT}"
  ${SUDO} dpkg-deb -x "${TMP}/libc6.deb" "${SYSROOT}"
fi
# The package's loader symlink is absolute; QEMU's -L prefix needs it relative.
${SUDO} ln -sfn ../lib/x86_64-linux-gnu/ld-linux-x86-64.so.2 "${SYSROOT}/lib64/ld-linux-x86-64.so.2"

# 4. x86_64 server + native arm64 harness, from the same release.
mkdir -p "${TARGET_DIR}/libexec"
fetch_binary() { # <arch> <file> <expected e_machine>
  local dest="${TARGET_DIR}/libexec/$2"
  if [[ "$(elf_machine "${dest}")" == "$3" ]]; then
    return
  fi
  say "Downloading $2 ($1, ${ACP_VERSION})"
  curl -fsSL "${ACP_BASE}-$1.zip" -o "${TMP}/acp-$1.zip"
  unzip -q -o -j "${TMP}/acp-$1.zip" "$2" -d "${TARGET_DIR}/libexec"
  rm -f "${TMP}/acp-$1.zip"
  chmod 0755 "${dest}"
}
fetch_binary x86_64 agy_acp_server.par 62
fetch_binary arm64 localharness_external 183

# 5. Wrapper at the path the meta-harness server looks up.
say "Writing wrapper ${TARGET_DIR}/agy_acp_server.par"
cat > "${TARGET_DIR}/agy_acp_server.par" <<EOF
#!/bin/sh
# Generated by install-antigravity-acp-linux-arm-sandbox.sh (sandbox only).
# Runs the x86_64 ACP server under QEMU; localharness_external next to it stays native.
# --uid: started as root, Google's init otherwise drops to \`nobody\`, which cannot read
# \$HOME/.gemini, so login fails with "Onboarding failed".
exec "${QEMU_DIR}/bin/qemu-x86_64" -L "${SYSROOT}" -E LD_LIBRARY_PATH="${SYSROOT}/lib/x86_64-linux-gnu" \\
  "${TARGET_DIR}/libexec/agy_acp_server.par" --uid="\$(id -un)" "\$@"
EOF
chmod 0755 "${TARGET_DIR}/agy_acp_server.par"
# meta-harness sets ANTIGRAVITY_HARNESS_PATH only when the harness sits next to the server.
ln -sfn libexec/localharness_external "${TARGET_DIR}/localharness_external"

# 6. Smoke test: the server must answer ACP initialize.
say "Smoke test: ACP initialize (slow under emulation)"
init='{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":1,"clientCapabilities":{}}}'
mkfifo "${TMP}/stdin"
"${TARGET_DIR}/agy_acp_server.par" <"${TMP}/stdin" >"${TMP}/init.out" 2>/dev/null &
server_pid=$!
exec 3>"${TMP}/stdin"
echo "${init}" >&3
for _ in $(seq 1 90); do
  grep -q '"agentInfo"' "${TMP}/init.out" 2>/dev/null && break
  kill -0 "${server_pid}" 2>/dev/null || break
  sleep 2
done
exec 3>&-  # EOF on stdin lets the server exit
kill "${server_pid}" 2>/dev/null || true
wait "${server_pid}" 2>/dev/null || true
reply="$(head -1 "${TMP}/init.out")"
if [[ "${reply}" == *'"agentInfo"'* ]]; then
  say "OK: $(grep -oE '"version":"[^"]*"' <<<"${reply}" | tail -1)"
else
  echo "Smoke test failed; reply: ${reply:-<none>}" >&2
  exit 1
fi
